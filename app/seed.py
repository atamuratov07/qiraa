def build_passage(data: PassageData) -> Passage:
    """Turn one entry of PASSAGES into a Passage with its questions and options."""
    questions: list[Question] = []
    for position, q in enumerate(data["questions"], start=1):
        correct = LETTERS.find(q["answer"])
        if not 0 <= correct < len(q["options"]):
            raise ValueError(
                f"{data['slug']}, question {position}: answer {q['answer']!r} "
                f"is not one of its {len(q['options'])} options"
            )
        options = [
            Option(position=i, text=text, is_correct=(i - 1 == correct))
            for i, text in enumerate(q["options"], start=1)
        ]
        questions.append(
            Question(
                position=position,
                prompt=q["prompt"],
                explanation=q["explanation"],
                options=options,
            )
        )
    return Passage(
        slug=data["slug"],
        title=data["title"],
        level=data["level"],
        text=data["text"],
        translation_ru=data["translation_ru"],
        questions=questions,
    )


def seed(db: Session) -> tuple[list[str], list[str]]:
    """Add every passage whose slug isn't in the database yet. Returns (added, skipped)."""
    added: list[str] = []
    skipped: list[str] = []
    for data in PASSAGES:
        exists = db.scalar(select(Passage.id).where(Passage.slug == data["slug"]))
        if exists is not None:
            skipped.append(data["slug"])
            continue
        db.add(build_passage(data))
        added.append(data["slug"])
    db.commit()
    return added, skipped


def main() -> None:
    with SessionLocal() as db:
        added, skipped = seed(db)
    print(f"Added {len(added)}: {', '.join(added) or '-'}")
    print(f"Skipped {len(skipped)} (already there): {', '.join(skipped) or '-'}")


if __name__ == "__main__":
    main()
